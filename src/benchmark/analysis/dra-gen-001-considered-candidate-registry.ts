/**
    * DRA-GEN-001 Phase 0 — Considered-Candidate Registry
    *
    * This is a REVIEW/PROTOCOL artefact, not an engineering or acquisition
    * artefact. It changes no production evaluator behaviour.
    *
    * Purpose: Section 5 of the DRA-GEN-001 blind generalisation protocol
    * requires excluding, from the blind-test sampling frame, every document
    * that any DRA contributor has already inspected for the purpose of
    * assessing DRA suitability — not just the 33 admitted development-corpus
    * documents, but every candidate ever considered during any DRA-ACQ
    * discovery/candidate-discovery programme, whether it was admitted,
    * rejected, deferred, or externally blocked (e.g. Cloudflare-blocked
    * OBR/Ofwat/Ofcom/CBO/BLS/GAO/CDC-MMWR candidates). Once a human has looked
    * at a document to judge whether DRA would handle it well, that document
    * can no longer serve as a genuinely blind test unit.
    *
    * Rather than hand-transcribing this list into prose (error-prone, and
    * unverifiable against the actual discovery-programme source), this module
    * is generated by statically scanning every file under
    * `benchmark/acquisition/discovery/` and `benchmark/acquisition/__tests__/`
    * (plus the acquisition module files themselves) for:
    *
    *   - every string literal shaped like an HTTP(S) URL, normalised to
    *     `origin + pathname` (query strings/fragments stripped, lowercased),
    *     since several discovery programmes reference the same underlying
    *     source via slightly different query parameters;
    *   - every string literal assigned to a `candidateId:` field.
    *
    * This is a coarse, deliberately over-inclusive match target: it is safe
    * for this exclusion list to be broader than strictly necessary (a
    * false-positive exclusion merely means one fewer eligible candidate in the
    * frame), but it must never be under-inclusive (a false negative would
    * silently readmit an already-inspected document into a "blind" sample).
    *
    * Regenerate by re-running the extraction script recorded in
    * `docs/dra/DRA-GEN-001-BLIND-GENERALISATION-PROTOCOL.md` Section 5 if new
    * discovery programmes are added before DRA-GEN-001 sampling begins. This
    * module must not be regenerated after the blind sample is drawn without
    * declaring a protocol amendment (see protocol Section 16/19).
    */

    /** Normalises a URL the same way this registry's generator did: origin + pathname, no trailing slash, lowercased. */
    export function normalizeConsideredUrl(url: string): string {
    try {
      const parsed = new URL(url);
      return (parsed.origin + parsed.pathname).replace(/\/$/, "").toLowerCase();
    } catch {
      return url.toLowerCase();
    }
    }

